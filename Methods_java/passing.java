package Methods_java;

public class passing
{
    static void main(String[] args)
    {
        sum(4,3);
        sub(9,8);
    }
    public static void sum(int a, int b)
    {
        System.out.println(a+b);
    }
    public static void sub(int c , int d)
    {
        System.out.println(c-d);
    }
}

